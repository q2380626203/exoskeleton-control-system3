FAQ = """
Q1: 串口连接失败怎么办？
A1:
   - 检查串口号是否正确（Windows: COM3, Linux: /dev/ttyUSB0）
   - 检查波特率是否为115200
   - 检查ESP32是否正常工作
   - 尝试关闭其他占用串口的程序

Q2: 采集到的数据格式不对？
A2:
   - 确认ESP32固件中printf格式为: motors:0.123,1.234,...
   - 检查是否有其他调试信息干扰
   - 尝试在代码中过滤掉非数据行

Q3: 自动标注结果不准确？
A3:
   - 调整静止阈值参数 --threshold (默认2.0)
   - 调整平滑窗口参数 --smooth (默认5)
   - 使用交互式工具手动修正

Q4: 找不到完整周期？
A4:
   - 检查标注是否包含完整的 IDLE→LIFTING→PRESSING→IDLE
   - 适当延长数据采集时间
   - 检查运动是否规律

Q5: 如何调试标注算法？
A5:
   - 查看生成的可视化图片
   - 检查统计报告中的阶段分布
   - 使用交互式工具逐段检查

Q6: 生成的C头文件如何使用？
A6:
   - 将.h文件复制到ESP32项目的main/目录
   - 在speed_follow_mode.cpp中 #include "ideal_curves_xxx.h"
   - 使用数组: ideal_flat_ground_m1_lifting_vel[i]

Q7: NPZ文件如何加载？
A7:
   import numpy as np
   data = np.load('训练数据_平地_m1.npz')
   X = data['X']
   y_phase = data['y_phase']
   y_params = data['y_params']
"""

