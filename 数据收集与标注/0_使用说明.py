工作流程 = """
┌──────────────────────────────────────────────────────────────────┐
│                         数据收集与标注流程                         │
└──────────────────────────────────────────────────────────────────┘

步骤1: 串口数据采集 (1_串口数据采集.py)
├─ 连接ESP32串口
├─ 实时采集 motors:... 数据
├─ 保存为CSV文件
└─ 输出: 平地数据.csv, 爬楼数据.csv

步骤2: 数据自动标注 (2_数据自动标注.py)
├─ 加载CSV数据
├─ 自动标注运动阶段 (静止/抬腿/压腿)
├─ 可视化标注结果
└─ 输出: 平地数据_已标注.csv, 标注可视化.png, 统计报告.txt

步骤3: 交互式标注修正 (3_交互式标注修正.py) [可选]
├─ 可视化速度曲线和标注
├─ 拖动鼠标框选修正错误标注
├─ 保存修正结果
└─ 输出: 修正后的CSV文件

步骤4: 理想曲线提取 (4_理想曲线提取.py)
├─ 识别完整运动周期
├─ 提取并平均各阶段曲线
├─ 导出C头文件
└─ 输出: ideal_curves_平地_m1.h, 理想曲线可视化.png

步骤5: 训练数据生成 (5_训练数据生成.py)
├─ 生成滑动窗口数据
├─ 生成参数调整标签
├─ 保存为NPZ格式
└─ 输出: 训练数据_平地_m1.npz, 统计报告.txt
"""

